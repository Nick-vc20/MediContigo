
CREATE TABLE IF NOT EXISTS administrador (
    id INT AUTO_INCREMENT PRIMARY KEY,
    correo VARCHAR(255) NOT NULL,
    contrasena VARCHAR(255) NOT NULL
);

CREATE TABLE IF NOT EXISTS centros_medicos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    tipo VARCHAR(50) NOT NULL,
    direccion VARCHAR(255) NOT NULL,
    latitud DECIMAL(10, 8) NOT NULL,
    longitud DECIMAL(11, 8) NOT NULL,
    costo_consulta DECIMAL(10,2) DEFAULT 0.00,
    tiempo_espera VARCHAR(50) DEFAULT 'No especificado',
    estado VARCHAR(20) DEFAULT 'ACTIVO',
    telefono VARCHAR(30),
    nivel_ocupacion VARCHAR(10) DEFAULT 'BAJO',
    fecha_registro TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS especialidad (
    id INT AUTO_INCREMENT PRIMARY KEY,
    centro_id INT NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    descripcion VARCHAR(255),
    estado BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_esp_centro FOREIGN KEY (centro_id) REFERENCES centros_medicos(id),
    CONSTRAINT uq_esp_centro_nombre UNIQUE (centro_id, nombre)
);

CREATE TABLE IF NOT EXISTS horario_especialidad (
    id INT AUTO_INCREMENT PRIMARY KEY,
    especialidad_id INT NOT NULL,
    dia_semana INT NOT NULL,        
    hora_inicio TIME NOT NULL,
    hora_fin TIME NOT NULL,
    CONSTRAINT fk_hor_esp FOREIGN KEY (especialidad_id) REFERENCES especialidad(id),
    CONSTRAINT chk_dia CHECK (dia_semana BETWEEN 1 AND 7),
    CONSTRAINT chk_horas CHECK (hora_fin > hora_inicio)
);

CREATE TABLE IF NOT EXISTS medicos (
    id INT AUTO_INCREMENT PRIMARY KEY,
    nombre_completo VARCHAR(150) NOT NULL,
    cmp VARCHAR(30) NOT NULL UNIQUE,
    especialidad_id INT NOT NULL,
    centro_id INT NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_ingreso DATE NOT NULL,
    FOREIGN KEY (especialidad_id) REFERENCES especialidad(id),
    FOREIGN KEY (centro_id) REFERENCES centros_medicos(id)
);


-- HU-17: Pacientes registrados (correo único, contraseña cifrada con BCrypt)

CREATE TABLE IF NOT EXISTS pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_completo VARCHAR(80) NOT NULL,
    correo VARCHAR(120) NOT NULL,
    contrasena_hash VARCHAR(100) NOT NULL,
    acepta_tratamiento_datos BOOLEAN NOT NULL,
    fecha_aceptacion_datos TIMESTAMP NOT NULL,
    fecha_registro TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_paciente_correo UNIQUE (correo),
    CONSTRAINT chk_paciente_acepta_datos CHECK (acepta_tratamiento_datos = TRUE)
);

-- HU-13: Reseñas y calificaciones de centros médicos

CREATE TABLE IF NOT EXISTS resenas (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    centro_id INT NOT NULL,

    -- HU-18: paciente autenticado que publicó la reseña
    paciente_id BIGINT,

    nombre_paciente VARCHAR(80) NOT NULL,

    puntuacion INT NOT NULL,

    comentario VARCHAR(1000) NOT NULL,

    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',

    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    -- HU-14: auditoría y moderación
    -- Alertas del filtro automático de contenido (códigos separados por coma)
    alertas_contenido VARCHAR(255),
    motivo_moderacion VARCHAR(255),
    moderado_por VARCHAR(255),
    fecha_moderacion TIMESTAMP,

    CONSTRAINT chk_resena_estado
        CHECK (estado IN ('PENDIENTE', 'PUBLICADA', 'RECHAZADA', 'OCULTA')),

    CONSTRAINT fk_resena_centro
        FOREIGN KEY (centro_id)
        REFERENCES centros_medicos(id),

    CONSTRAINT fk_resena_paciente
        FOREIGN KEY (paciente_id)
        REFERENCES pacientes(id),

    CONSTRAINT chk_resena_puntuacion
        CHECK (puntuacion BETWEEN 1 AND 5)
);


-- HU-08: Tarifario de costos por especialidad

CREATE TABLE IF NOT EXISTS tarifa (
    id INT AUTO_INCREMENT PRIMARY KEY,
    especialidad_id INT NOT NULL UNIQUE,
    precio_aproximado DECIMAL(10,2) NOT NULL,
    moneda VARCHAR(3) NOT NULL DEFAULT 'PEN',

    CONSTRAINT fk_tarifa_especialidad
        FOREIGN KEY (especialidad_id)
        REFERENCES especialidad(id),

    CONSTRAINT chk_tarifa_precio
        CHECK (precio_aproximado >= 0)
);
